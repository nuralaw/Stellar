// Writes content/bank/REVIEW.md: hidden (low-confidence) and medium-confidence answers to check by hand.
// Usage: npm run bank:review
import fs from "node:fs";
import path from "node:path";

const BANK = path.resolve(import.meta.dirname, "..", "content", "bank");
const dir = path.join(BANK, "answers");
const low = [];
const med = [];
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  for (const x of JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"))) {
    if (x.confidence === "low") low.push(x);
    else if (x.confidence === "medium") med.push(x);
  }
}

const ans = (x) => (Array.isArray(x.answer) ? x.answer.join(" / ") : x.answer);
const cell = (s) => String(s ?? "").replace(/\|/g, "/").replace(/\s*\n\s*/g, " ");
const table = (rows, def) =>
  "| id | answer | note |\n|---|---|---|\n" + rows.map((x) => `| ${x.id} | ${cell(ans(x))} | ${cell(x.note || def)} |`).join("\n");

const md = `# Question bank — items to review

Generated by \`npm run bank:review\` from content/bank/answers/*.json.

- **Hidden** items (low confidence) are not shown on the site until reviewed.
- **Medium** items are live but worth a second look.

To fix an item: correct the text in content/bank/fixes.json (fields: prompt, passage, choices, table, choicesImage)
or the answer in its answers file, set \`"confidence": "high"\`, then run \`npm run bank:build\` and \`npm run bank:review\`.

## Hidden (low confidence) — ${low.length}

${table(low, "")}

## Live, medium confidence — ${med.length}

${table(med, "close call between two choices")}
`;
fs.writeFileSync(path.join(BANK, "REVIEW.md"), md);
console.log(`REVIEW.md: ${low.length} hidden, ${med.length} medium`);
