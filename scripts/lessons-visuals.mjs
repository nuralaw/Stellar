// Lesson visuals (src/components/lessons/visuals/<slug>.tsx): check, preview, index.
//   npm run lessons:visuals -- <slug>…   check each visual, type-check it, render it and save a storyboard PNG
//                                        (frames across the loop + the still frame, light and dark theme)
//   npm run lessons:visuals              check every visual (no PNGs) and that index.ts lists them all
//   npm run lessons:visuals -- --index   rewrite index.ts from the files in the folder
// Errors fail the run (exit 1); warnings pass. Rules: src/components/lessons/visuals/README.md.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "src/components/lessons/visuals");
const cacheRoot = path.join(root, "node_modules/.cache/lesson-visuals");
const NOT_VISUALS = new Set(["kit", "index", "Stage"]);
const CHROME = ["C:/Program Files/Google/Chrome/Application/chrome.exe", "C:/Program Files (x86)/Google/Chrome/Application/chrome.exe", "/usr/bin/google-chrome", "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"].find((p) => fs.existsSync(p));
const FONT = path.join(root, "node_modules/next/dist/esm/next-devtools/server/font/geist-latin.woff2");

const allSlugs = () =>
  fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".tsx") && !NOT_VISUALS.has(path.basename(f, ".tsx")))
    .map((f) => path.basename(f, ".tsx"))
    .sort();

const camel = (s) => s.replace(/-+([a-z0-9])/g, (_, c) => c.toUpperCase());

function writeIndex() {
  const slugs = allSlugs();
  const src = [
    "// Generated by `npm run lessons:visuals -- --index` from the files in this folder. Don't edit by hand.",
    'import type { ComponentType } from "react";',
    ...slugs.map((s) => `import * as ${camel(s)} from "./${s}";`),
    "",
    "/** Lesson visual per lesson slug. */",
    "export const VISUALS: Record<string, { Visual: ComponentType; alt: string }> = {",
    ...slugs.map((s) => `  ${JSON.stringify(s)}: { Visual: ${camel(s)}.default, alt: ${camel(s)}.alt },`),
    "};",
    "",
  ].join("\n");
  fs.writeFileSync(path.join(dir, "index.ts"), src);
  console.log(`index.ts: ${slugs.length} visuals`);
}

/** Static rules. Returns { errors, warns }. */
function lint(slug, src) {
  const errors = [];
  const warns = [];
  const pre = `v-${slug}-`;
  if (/["']use client["']/.test(src)) errors.push('no "use client": visuals are server-rendered SVG + CSS');
  if (/\buse(State|Effect|Ref|Memo|Callback|LayoutEffect|Reducer|Context|Id)\b/.test(src)) errors.push("no React hooks in a visual");
  for (const m of src.matchAll(/^import .* from ["']([^"']+)["']/gm)) if (m[1] !== "./kit" && m[1] !== "react") errors.push(`import from "${m[1]}" (only ./kit and react)`);
  if (!/export const alt\s*=/.test(src)) errors.push("missing `export const alt = \"…\"` (one sentence: what the animation shows)");
  if (!/export default function/.test(src)) errors.push("missing `export default function Visual()`");
  if (!/<Svg\b/.test(src)) errors.push("draw inside <Svg label={alt}> from ./kit");
  if (/<(animate|animateTransform|animateMotion|set)\b/.test(src)) errors.push("no SMIL (<animate>…): animate with CSS keyframes so the page can pause it");
  if (/<(image|foreignObject|script|use)\b/.test(src)) errors.push("no <image>, <foreignObject>, <script> or <use>");
  if (/https?:\/\//.test(src)) errors.push("no URLs");
  if (/#[0-9a-fA-F]{3,8}\b/.test(src) || /\b(rgb|rgba|hsl|hsla)\(/.test(src)) errors.push("hard-coded color: use C.* from ./kit (theme variables)");
  const fills = [...src.matchAll(/\b(?:fill|stroke)=["']([a-z]+)["']/g)].map((m) => m[1]).filter((c) => !["none", "currentColor"].includes(c));
  if (fills.length) errors.push(`named color(s) ${[...new Set(fills)].join(", ")}: use C.* from ./kit`);
  // CSS names
  for (const m of src.matchAll(/@keyframes\s+([\w-]+)/g)) if (!m[1].startsWith(pre)) errors.push(`keyframes "${m[1]}" must start with ${pre}`);
  const cssBlocks = [...src.matchAll(/`([^`]*)`/g)].map((m) => m[1]).filter((b) => /[{}]/.test(b) && /:\s*[^;]+;|@keyframes/.test(b));
  for (const b of cssBlocks)
    for (const m of b.replace(/\$\{[^}]*\}/g, "").matchAll(/(?:^|[\s,{}>+~])\.(-?[_a-zA-Z][\w-]*)/g)) if (!m[1].startsWith(pre)) errors.push(`CSS class ".${m[1]}" must start with ${pre}`);
  for (const m of src.matchAll(/className=(?:"([^"]*)"|\{`([^`]*)`\}|'([^']*)')/g)) {
    const val = (m[1] ?? m[2] ?? m[3]).replace(/\$\{[^}]*\}/g, " ");
    for (const c of val.split(/\s+/).filter(Boolean)) if (!c.startsWith(pre)) errors.push(`className "${c}" must start with ${pre}`);
  }
  for (const m of src.matchAll(/\bid=["{]`?([^"`}]*)/g)) if (!m[1].startsWith(pre)) errors.push(`id "${m[1]}" must start with ${pre}`);
  // Timing
  const durs = [...src.matchAll(/animation(?:-duration)?:\s*([\d.]+)s/g)].map((m) => Number(m[1]));
  if (!durs.length) errors.push("no `animation: <N>s …` found: the visual must animate");
  for (const d of durs) if (d < 4 || d > 12) warns.push(`animation of ${d}s (aim for one 6–10 s loop)`);
  if (new Set(durs).size > 1) warns.push(`several durations (${[...new Set(durs)].join(", ")} s): one shared loop length keeps the beats in sync`);
  if (!/infinite/.test(src)) errors.push("the animation must loop (infinite)");
  const kb = Buffer.byteLength(src) / 1024;
  if (kb > 16) warns.push(`${kb.toFixed(1)} KB (keep it under 16 KB)`);
  return { errors, warns };
}

function typecheck(file) {
  const tsc = path.join(root, "node_modules/typescript/bin/tsc");
  try {
    execFileSync(process.execPath, [tsc, "--noEmit", "--jsx", "react-jsx", "--strict", "--skipLibCheck", "--module", "esnext", "--moduleResolution", "bundler", "--target", "es2022", "--lib", "es2022,dom", "--types", "react", file], {
      cwd: root,
      stdio: "pipe",
    });
    return [];
  } catch (e) {
    return String(e.stdout || e.message)
      .split("\n")
      .filter((l) => l.trim())
      .slice(0, 12)
      .map((l) => `tsc: ${l.replace(root, "").trim()}`);
  }
}

function transpile(file) {
  return ts
    .transpileModule(fs.readFileSync(file, "utf8"), { compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } })
    .outputText.replace(/from ["']\.\/kit["']/g, 'from "./kit.mjs"');
}

async function render(slug) {
  const out = path.join(cacheRoot, slug);
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, "kit.mjs"), transpile(path.join(dir, "kit.tsx")));
  fs.writeFileSync(path.join(out, "visual.mjs"), transpile(path.join(dir, `${slug}.tsx`)));
  const { createElement } = await import("react");
  const { renderToStaticMarkup } = await import("react-dom/server");
  const mod = await import(`${pathToFileURL(path.join(out, "visual.mjs")).href}?t=${Date.now()}`);
  if (typeof mod.default !== "function") throw new Error("default export is not a component");
  return { out, svg: renderToStaticMarkup(createElement(mod.default)), alt: mod.alt };
}

const THEMES = {
  light: "--bg:#f5f5f4;--surface:#ffffff;--surface-2:#ececea;--ink:#1c1c1e;--muted:#6b6b70;--line:#e2e2df;--primary:#ea580c;--primary-soft:#fff1e6;--success:#15803d;--success-soft:#dcfce7;--danger:#b91c1c;--danger-soft:#fee2e2;",
  dark: "--bg:#111112;--surface:#1a1a1c;--surface-2:#232326;--ink:#ededee;--muted:#9d9da3;--line:#2b2b2f;--primary:#fb923c;--primary-soft:#2e1d10;--success:#4ade80;--success-soft:#0f2a1a;--danger:#f87171;--danger-soft:#2f1414;",
};
const FRAMES = [0.1, 0.25, 0.4, 0.55, 0.7, 0.85, 0.95];

function storyboard(out, slug, svg) {
  const cell = (theme, f) =>
    `<figure><div class="isle" style="${THEMES[theme]}" data-f="${f}">${svg}</div><figcaption>${f === "still" ? "still (reduced motion)" : `${Math.round(f * 100)}% of the loop`}</figcaption></figure>`;
  const row = (theme) => `<section style="${THEMES[theme]}background:var(--bg);color:var(--muted)"><h2>${slug} · ${theme}</h2><div class="grid">${[...FRAMES, "still"].map((f) => cell(theme, f)).join("")}</div></section>`;
  const html = `<!doctype html><html><head><meta charset="utf-8"><style>
@font-face{font-family:Geist;src:url("${pathToFileURL(FONT).href}") format("woff2");font-weight:100 900}
body{margin:0;font-family:Geist,"Segoe UI",system-ui,sans-serif}
section{padding:14px 16px 6px}h2{margin:0 0 8px;font:600 13px Geist,sans-serif}
.grid{display:grid;grid-template-columns:repeat(4,320px);gap:10px 16px}
figure{margin:0}.isle{width:320px;height:180px;background:var(--surface);border-radius:14px;outline:1px solid var(--line)}
figcaption{font-size:11px;margin-top:3px}
.isle[data-f="still"] *{animation:none!important}
</style></head><body>${row("light")}${row("dark")}<script>
for (const el of document.querySelectorAll(".isle")) {
  const f = el.dataset.f; if (f === "still") continue;
  const anims = el.getAnimations({ subtree: true });
  const T = Math.max(0, ...anims.map((a) => a.effect.getComputedTiming().duration || 0));
  for (const a of anims) { a.pause(); a.currentTime = T * Number(f); }
}
</script></body></html>`;
  const htmlFile = path.join(out, "storyboard.html");
  fs.writeFileSync(htmlFile, html);
  if (!CHROME) return { html: htmlFile, png: null };
  const png = path.join(out, "storyboard.png");
  fs.rmSync(png, { force: true });
  execFileSync(
    CHROME,
    ["--headless=new", "--disable-gpu", "--hide-scrollbars", "--no-first-run", "--no-default-browser-check", `--user-data-dir=${path.join(out, "chrome")}`, "--window-size=1360,950", "--virtual-time-budget=2000", `--screenshot=${png}`, pathToFileURL(htmlFile).href],
    { stdio: "pipe", timeout: 60000 },
  );
  return { html: htmlFile, png: fs.existsSync(png) ? png : null };
}

// ---- main ----
const args = process.argv.slice(2);
if (args.includes("--index")) {
  writeIndex();
  process.exit(0);
}
const preview = args.length > 0;
const slugs = preview ? args.map((a) => path.basename(a, ".tsx")) : allSlugs();
let errorCount = 0;
for (const slug of slugs) {
  const file = path.join(dir, `${slug}.tsx`);
  if (!fs.existsSync(file)) {
    console.log(`✗ ${slug}: no file src/components/lessons/visuals/${slug}.tsx`);
    errorCount++;
    continue;
  }
  const src = fs.readFileSync(file, "utf8");
  const { errors, warns } = lint(slug, src);
  if (preview) errors.push(...typecheck(file));
  let pic = null;
  if (preview && !errors.length) {
    try {
      const r = await render(slug);
      if (!r.alt || typeof r.alt !== "string") errors.push("alt must be a string");
      else if (r.alt.length > 200) warns.push(`alt is ${r.alt.length} chars (keep it under 200)`);
      pic = storyboard(r.out, slug, r.svg);
    } catch (e) {
      errors.push(`render failed: ${e.message}`);
    }
  }
  console.log(`${errors.length ? "✗" : "✓"} ${slug}`);
  for (const e of errors) console.log(`  error: ${e}`);
  for (const w of warns) console.log(`  warn:  ${w}`);
  if (pic?.png) console.log(`  storyboard: ${pic.png}`);
  else if (pic) console.log(`  storyboard (Chrome not found, open in a browser): ${pic.html}`);
  errorCount += errors.length;
}
if (!preview) {
  const idx = fs.existsSync(path.join(dir, "index.ts")) ? fs.readFileSync(path.join(dir, "index.ts"), "utf8") : "";
  const missing = slugs.filter((s) => !idx.includes(`from "./${s}"`));
  if (missing.length) {
    console.log(`index.ts is missing: ${missing.join(", ")} (run npm run lessons:visuals -- --index)`);
    errorCount++;
  }
}
console.log(errorCount ? `\n${errorCount} error(s)` : "\nall good");
process.exit(errorCount ? 1 : 0);
